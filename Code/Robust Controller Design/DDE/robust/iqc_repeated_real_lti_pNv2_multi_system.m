%% iqc_repeated_real_lti_pNv2_multi_system.m
% IQC/LMI script for testing multiple LFR systems with a repeated real LTI
% parametric uncertainty, using the p = N*v2 augmentation.
%
% Uncertain interconnection:
%   q = G_qp p + G_qw w
%   z = G_zp p + G_zw w
%   p = delta * I_r * q,     delta in R, |delta| <= alpha.
%
% Dynamic multiplier basis:
%   v1 = alpha*(psi_nu kron I_r)*q
%   v2 =        (psi_nu kron I_r)*p
%
% Since the first basis element is psi_0(s)=1, the first r components of v2
% are exactly p. Hence
%   p = N*v2,   N = [I_r 0 ... 0].
%
% This file treats v2 as the IQC input and builds the augmented map
%   [v2; w]  ->  [v1; z]
% with p substituted by N*v2. This avoids adding a dynamic multiplier output
% driven by p in the main plant realization. The resulting test is sufficient
% for analysis because it enforces the dissipation inequality for all v2,
% including the subset v2=(psi kron I_r)*p generated by true trajectories.
%
% Dependencies:
%   - MATLAB Control System Toolbox
%   - YALMIP
%   - SDP solver supported by YALMIP, e.g. MOSEK, SeDuMi, SDPT3
%
% How to use:
%   1. Add/replace entries in the "Plants to test" section.
%   2. Each plant must be an LFR realization with matrices
%      A, Bp, Bw, Cq, Dqp, Dqw, Cz, Dzp, Dzw.
%   3. This file assumes np = nq = r and Delta = delta*I_r.

clear; clc; close all;
yalmip('clear');

%% Solver and analysis settings
solverName = '';        % examples: 'mosek', 'sedumi', 'sdpt3'; empty lets YALMIP choose
lmiTol     = 1e-8;      % strictness surrogate; try 1e-9 or 0 if numerically fragile

nuList     = 0:3;
rho        = -1;
basisType  = '12a';
alphaGrid  = linspace(0,1,51);

%% Plants to test
plants = {};

% 1) Paper Example 8.1. This is the full LFR from Eq. (94).
plants{end+1} = make_example81_lfr();

% 2) Template for your own system. Uncomment and replace the matrices.
%    Dimensions must satisfy:
%       A    nx x nx
%       Bp   nx x r       Bw   nx x nw
%       Cq   r  x nx      Dqp  r  x r       Dqw  r  x nw
%       Cz   nz x nx      Dzp  nz x r       Dzw  nz x nw
%    Then Delta = delta*I_r closes p = Delta*q.
%
% A   = [-1  0; 0 -2];
% Bp  = [1; 0];
% Bw  = [0; 1];
% Cq  = [1 0];
% Dqp = 0;
% Dqw = 0;
% Cz  = [0 1];
% Dzp = 0;
% Dzw = 0;
% plants{end+1} = make_lfr('my custom 1x1 uncertainty plant', ...
%     A,Bp,Bw,Cq,Dqp,Dqw,Cz,Dzp,Dzw);

%% Run all plants
allResults = cell(numel(plants),1);

for kPlant = 1:numel(plants)
    plant = plants{kPlant};
    validate_repeated_scalar_lfr(plant);

    fprintf('\n=== Plant %d/%d: %s ===\n',kPlant,numel(plants),plant.name);
    fprintf('nx=%d, r=np=nq=%d, nw=%d, nz=%d\n', ...
        size(plant.A,1), size(plant.Bp,2), size(plant.Bw,2), size(plant.Cz,1));

    gammaBound = nan(numel(alphaGrid),numel(nuList));
    statusText = strings(numel(alphaGrid),numel(nuList));

    for j = 1:numel(nuList)
        nu = nuList(j);
        fprintf('  nu = %d\n',nu);
        for i = 1:numel(alphaGrid)
            alpha = alphaGrid(i);
            out = iqc_repeated_real_lti_bound_pNv2(plant,alpha,nu,rho,basisType,solverName,lmiTol);
            gammaBound(i,j) = out.gamma;
            statusText(i,j) = out.status;
            fprintf('    alpha = %.3f: gamma = %.6g (%s)\n',alpha,out.gamma,out.status);
        end
    end

    result = struct();
    result.plant = plant;
    result.alphaGrid = alphaGrid;
    result.nuList = nuList;
    result.rho = rho;
    result.basisType = basisType;
    result.gammaBound = gammaBound;
    result.statusText = statusText;
    allResults{kPlant} = result;

    figure('Name',['IQC p=Nv2 bounds - ' plant.name]);
    plot(alphaGrid,gammaBound,'LineWidth',1.5);
    ylim([0,100])
    grid on;
    xlabel('\alpha');
    ylabel('\gamma');
    legend(compose('\\nu = %d',nuList),'Location','NorthWest');
    title(['p=Nv_2 IQC upper bounds for ' plant.name],'Interpreter','none');
end

